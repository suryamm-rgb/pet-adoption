import { Router } from "express";
import * as c from "../controllers/bookingController.js";
import { requireAuth, requireRole } from "../middleware/auth.js";
import { upload } from "../middleware/upload.js";
import { validate } from "../middleware/validate.js";
import { wrap } from "../utils/http.js";
import { booking, social } from "../utils/schemas.js";

const r = Router();
r.use(requireAuth);
r.post("/", requireRole("owner"), validate(booking.create), wrap(c.create));
r.get("/mine", wrap(c.mine));
r.get("/reviews/mine", wrap(c.myReviews));
r.get("/:id", wrap(c.get));
r.get("/:id/invoice", wrap(c.invoice));
r.patch("/:id/accept", requireRole("caretaker"), wrap(c.accept));
r.patch("/:id/reject", requireRole("caretaker"), wrap(c.reject));
r.patch("/:id/cancel", validate(booking.cancel), wrap(c.cancel));
r.patch("/:id/complete", requireRole("owner"), wrap(c.complete));
r.post("/:id/instructions", requireRole("owner"), validate(booking.instruction), wrap(c.addInstruction));
r.patch("/:id/instructions/:iid/ack", requireRole("caretaker"), wrap(c.ackInstruction));
r.post("/:id/updates", requireRole("caretaker"), upload("files"), validate(social.update), wrap(c.postUpdate));
r.get("/:id/updates", wrap(c.listUpdates));
r.get("/:id/messages", wrap(c.listMessages));
r.post("/:id/messages", validate(social.message), wrap(c.postMessage));
r.post("/:id/reviews", validate(social.review), wrap(c.review));
r.post("/:id/disputes", upload("files"), validate(social.dispute), wrap(c.dispute));
r.post("/:id/emergency", requireRole("caretaker"), wrap(c.emergency));
export default r;
