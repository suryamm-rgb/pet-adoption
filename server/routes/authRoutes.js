import { Router } from "express";
import rateLimit from "express-rate-limit";
import * as c from "../controllers/authController.js";
import { requireAuth } from "../middleware/auth.js";
import { validate } from "../middleware/validate.js";
import { wrap } from "../utils/http.js";
import { auth as s } from "../utils/schemas.js";

const limiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: process.env.NODE_ENV === "test" ? 1000 : 30, standardHeaders: true, legacyHeaders: false });
const r = Router();
r.post("/register", limiter, validate(s.register), wrap(c.register));
r.post("/login", limiter, validate(s.login), wrap(c.login));
r.post("/logout", c.logout);
r.get("/me", requireAuth, c.me);
r.patch("/me", requireAuth, validate(s.profile), wrap(c.updateMe));
r.delete("/me", requireAuth, limiter, validate(s.deleteAccount), wrap(c.deleteMe));
r.post("/change-password", requireAuth, limiter, validate(s.changePassword), wrap(c.changePassword));
r.post("/google", limiter, validate(s.google), wrap(c.google));
r.post("/phone/send-otp", requireAuth, limiter, wrap(c.phoneSend));
r.post("/phone/verify-otp", requireAuth, limiter, validate(s.otp), wrap(c.phoneVerify));
r.patch("/preferences", requireAuth, validate(s.prefs), wrap(c.preferences));
r.post("/push/subscribe", requireAuth, validate(s.pushSubscribe), wrap(c.pushSubscribe));
r.post("/push/unsubscribe", requireAuth, validate(s.pushUnsubscribe), wrap(c.pushUnsubscribe));
r.post("/logout-all", requireAuth, wrap(c.logoutAll));
r.post("/verify-email", validate(s.token), wrap(c.verifyEmail));
r.post("/resend-verification", limiter, requireAuth, wrap(c.resendVerification));
r.post("/forgot-password", limiter, validate(s.forgot), wrap(c.forgot));
r.post("/reset-password", limiter, validate(s.reset), wrap(c.reset));
r.post("/roles", requireAuth, validate(s.role), wrap(c.addRole));
export default r;
